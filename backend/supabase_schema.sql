-- Apply a stock movement atomically and write its history/audit record.
create or replace function public.apply_stock_change(
    p_product_id bigint,
    p_movement_type text,
    p_quantity integer,
    p_supplier_id bigint default null,
    p_reason text default null,
    p_changed_by uuid default null
)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
    old_quantity integer;
    new_quantity integer;
    movement_quantity integer;
    product_data jsonb;
begin
    if p_movement_type not in ('stock_in', 'stock_out', 'damaged', 'return', 'adjustment') then
        raise exception 'Unsupported stock movement type';
    end if;

    if p_quantity is null or p_quantity < 0 then
        raise exception 'Quantity cannot be negative';
    end if;

    if p_movement_type <> 'adjustment' and p_quantity = 0 then
        raise exception 'Quantity must be greater than zero';
    end if;

    select quantity
    into old_quantity
    from public.products
    where id = p_product_id
    for update;

    if not found then
        raise exception 'Product not found';
    end if;

    if p_movement_type in ('stock_in', 'return') then
        new_quantity := old_quantity + p_quantity;
        movement_quantity := p_quantity;
    elsif p_movement_type = 'adjustment' then
        new_quantity := p_quantity;
        movement_quantity := abs(new_quantity - old_quantity);
        if movement_quantity = 0 then
            raise exception 'New quantity is the same as current quantity';
        end if;
    else
        new_quantity := old_quantity - p_quantity;
        movement_quantity := p_quantity;
        if new_quantity < 0 then
            raise exception 'Insufficient stock: stock cannot become negative';
        end if;
    end if;

    update public.products
    set quantity = new_quantity, updated_at = now()
    where id = p_product_id;

    insert into public.stock_movements (
        product_id, movement_type, quantity, old_quantity, new_quantity,
        supplier_id, reason, changed_by
    )
    values (
        p_product_id, p_movement_type, movement_quantity, old_quantity, new_quantity,
        p_supplier_id, p_reason, p_changed_by
    );

    insert into public.audit_logs (
        user_id, action, table_name, record_id, old_data, new_data
    )
    values (
        p_changed_by,
        'stock_' || p_movement_type,
        'products',
        p_product_id::text,
        jsonb_build_object('quantity', old_quantity),
        jsonb_build_object('quantity', new_quantity)
    );

    select to_jsonb(product_row)
    into product_data
    from public.products as product_row
    where product_row.id = p_product_id;

    return product_data;
end;
$$;

revoke execute on function public.apply_stock_change(bigint, text, integer, bigint, text, uuid)
from public, anon, authenticated;
grant execute on function public.apply_stock_change(bigint, text, integer, bigint, text, uuid)
to service_role;

-- Confirm or cancel an AI-created request atomically. The backend calls these
-- functions with the service-role key only after validating the bearer token.
create or replace function public.confirm_stock_change_request(
    p_request_id bigint,
    p_approved_by uuid,
    p_actor_role text
)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
    request_row public.stock_change_requests%rowtype;
    product_row public.products%rowtype;
    product_data jsonb;
begin
    if p_actor_role not in ('staff', 'manager') then
        raise exception 'Invalid actor role';
    end if;

    select *
    into request_row
    from public.stock_change_requests
    where id = p_request_id
    for update;

    if not found then
        raise exception 'Stock change request not found';
    end if;
    if request_row.status <> 'pending' then
        raise exception 'Request is already %', request_row.status;
    end if;
    if p_actor_role <> 'manager' and request_row.requested_by <> p_approved_by then
        raise exception 'You can only manage your own stock-change requests';
    end if;
    if request_row.requested_action = 'adjustment' and p_actor_role <> 'manager' then
        raise exception 'Staff cannot confirm adjustment requests';
    end if;
    if request_row.requested_action not in ('stock_in', 'stock_out', 'damaged', 'return', 'adjustment') then
        raise exception 'Unsupported stock movement type';
    end if;
    if request_row.quantity is null or request_row.quantity <= 0 then
        raise exception 'Request quantity must be greater than zero';
    end if;

    select *
    into product_row
    from public.products
    where id = request_row.product_id
    for update;

    if not found then
        raise exception 'Product not found';
    end if;
    if not product_row.is_active then
        raise exception 'Product is inactive';
    end if;

    -- This function performs the locked quantity check, movement insert, and
    -- stock audit in the same transaction as the request status update.
    product_data := public.apply_stock_change(
        request_row.product_id,
        request_row.requested_action,
        request_row.quantity,
        request_row.supplier_id,
        request_row.reason,
        p_approved_by
    );

    update public.stock_change_requests
    set status = 'confirmed',
        approved_by = p_approved_by,
        confirmed_at = now()
    where id = p_request_id
    returning * into request_row;

    insert into public.audit_logs (
        user_id, action, table_name, record_id, old_data, new_data
    )
    values (
        p_approved_by,
        'ai_stock_request_confirmed',
        'stock_change_requests',
        p_request_id::text,
        jsonb_build_object('status', 'pending'),
        to_jsonb(request_row)
    );

    return jsonb_build_object(
        'request', to_jsonb(request_row),
        'product', product_data
    );
end;
$$;

revoke execute on function public.confirm_stock_change_request(bigint, uuid, text)
from public, anon, authenticated;
grant execute on function public.confirm_stock_change_request(bigint, uuid, text)
to service_role;

create or replace function public.cancel_stock_change_request(
    p_request_id bigint,
    p_cancelled_by uuid,
    p_actor_role text
)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
    request_row public.stock_change_requests%rowtype;
begin
    if p_actor_role not in ('staff', 'manager') then
        raise exception 'Invalid actor role';
    end if;

    select *
    into request_row
    from public.stock_change_requests
    where id = p_request_id
    for update;

    if not found then
        raise exception 'Stock change request not found';
    end if;
    if request_row.status <> 'pending' then
        raise exception 'Request is already %', request_row.status;
    end if;
    if p_actor_role <> 'manager' and request_row.requested_by <> p_cancelled_by then
        raise exception 'You can only manage your own stock-change requests';
    end if;

    update public.stock_change_requests
    set status = 'cancelled'
    where id = p_request_id
    returning * into request_row;

    insert into public.audit_logs (
        user_id, action, table_name, record_id, old_data, new_data
    )
    values (
        p_cancelled_by,
        'ai_stock_request_cancelled',
        'stock_change_requests',
        p_request_id::text,
        jsonb_build_object('status', 'pending'),
        to_jsonb(request_row)
    );

    return to_jsonb(request_row);
end;
$$;

revoke execute on function public.cancel_stock_change_request(bigint, uuid, text)
from public, anon, authenticated;
