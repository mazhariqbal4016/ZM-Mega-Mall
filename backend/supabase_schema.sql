select seed.name, seed.phone, seed.email, seed.address
from (
    values
        ('Ali Traders', '', '', ''),
        ('Nowshera Wholesale', '', '', ''),
        ('Pak Electronics', '', '', '')
) as seed(name, phone, email, address)
where not exists (
    select 1 from public.suppliers existing where existing.name = seed.name
);

