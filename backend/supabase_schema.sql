create table if not exists public.profiles (
    id uuid primary key,
    full_name text,
    email text unique,
    role text not null default 'staff' check (role in ('staff', 'manager')),
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.categories (
    id bigint generated by default as identity primary key,
    name text unique not null,
    description text,
    created_at timestamptz not null default now()
);

create table if not exists public.suppliers (
    id bigint generated by default as identity primary key,
    name text not null,
    phone text,
    email text,
    address text,
    created_at timestamptz not null default now()
);

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    name text not null,
    sku text unique not null,
    category_id bigint references public.categories(id) on delete set null,
    supplier_id bigint references public.suppliers(id) on delete set null,
    quantity integer not null default 0 check (quantity >= 0),
    minimum_stock integer not null default 5 check (minimum_stock >= 0),
    selling_price numeric(12, 2) check (selling_price >= 0),
    cost_price numeric(12, 2) check (cost_price >= 0),
    location text,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.stock_movements (
    id bigint generated by default as identity primary key,
    product_id bigint not null references public.products(id) on delete restrict,
    movement_type text not null check (
        movement_type in ('stock_in', 'stock_out', 'sale', 'damaged', 'return', 'adjustment')
    ),
    quantity integer not null check (quantity > 0),
    old_quantity integer not null check (old_quantity >= 0),
    new_quantity integer not null check (new_quantity >= 0),
    supplier_id bigint references public.suppliers(id) on delete set null,
    reason text,
    changed_by uuid,
    created_at timestamptz not null default now()
);

create table if not exists public.stock_change_requests (
    id bigint generated by default as identity primary key,
    product_id bigint not null references public.products(id) on delete restrict,
    requested_action text not null check (
        requested_action in ('stock_in', 'stock_out', 'sale', 'damaged', 'return', 'adjustment')
    ),
    quantity integer not null check (quantity > 0),
    supplier_id bigint references public.suppliers(id) on delete set null,
    reason text,
    requested_by uuid,
    status text not null default 'pending' check (
        status in ('pending', 'confirmed', 'cancelled', 'rejected')
    ),
    approved_by uuid,
    created_at timestamptz not null default now(),
    confirmed_at timestamptz
);

create table if not exists public.audit_logs (
    id bigint generated by default as identity primary key,
    user_id uuid,
    action text not null,
    table_name text not null,
    record_id text,
    old_data jsonb,
    new_data jsonb,
    created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
before update on public.products
for each row execute function public.set_updated_at();

